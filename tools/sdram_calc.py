#!/usr/bin/env python3
# sdram_calc.py -- M12L64322A(2S) timing->cycle derivations + address map.
# Source: ESMT datasheet (chubby75/5a-75b/datasheets, AC OPERATING PARAM,
# worst-case -7 grade column). Defines the constants rtl/wb_sdram.v must
# compute identically from its CLK_FREQ parameter (tb cross-checks via the
# --vh header). usage: python3 tools/sdram_calc.py [mhz...] | --vh <mhz>

import math, sys

# ns minima (worst case -7 grade); tCCD/tCDL/tRDL are clock counts (clk-free)
T_NS = dict(RRD=14, RCD=21, RP=21, RAS=42, RC=63, RFC=63)
T_MRD_CLK = 2                        # MRS->next command: 2 CLKs (clk-unit)
REF_MS, REF_ROWS = 64.0, 4096        # 64ms refresh period, 4K cycles
INIT_US = 200                        # power-up delay before any command
T_SAC = {2: 8, 3: 6}                 # CL -> CLK-to-valid-out max ns (-7)
T_OH, T_SU = 2, 2

def cyc(ns, mhz): return math.ceil(ns*mhz/1000)

def params(mhz):
    return {
        "T_RRD":  cyc(T_NS["RRD"], mhz),
        "T_RCD":  cyc(T_NS["RCD"], mhz),
        "T_RP":   cyc(T_NS["RP"], mhz),
        "T_RAS":  cyc(T_NS["RAS"], mhz),
        "T_RC":   cyc(T_NS["RC"], mhz),
        "T_RFC":  cyc(T_NS["RFC"], mhz),
        "T_MRD":  T_MRD_CLK,
        "T_REF":  int(REF_MS*1000*mhz/REF_ROWS),   # floor: conservative
        "T_INIT": cyc(INIT_US*1000, mhz),
    }

def report(mhz):
    per = 1000.0/mhz
    p = params(mhz)
    print(f"CLK={mhz}MHz (period {per:.2f}ns)")
    for k, v in p.items(): print(f"  {k:7s} = {v}")
    for k in ("RRD","RCD","RP","RAS","RC","RFC"):
        assert p["T_"+k]*per >= T_NS[k] - 1e-9, k
    for cl in (2, 3):
        print(f"  CL={cl}: capture edge = colcmd+{cl+2}; window {per:.1f}ns vs "
              f"tSAC(-7) {T_SAC[cl]}ns -> {'OK' if T_SAC[cl] < per else 'VIOLATION'}")
    print(f"  map: 1M words = col[7:0] ba[1:0] row[9:0]; "
          f"{256*4*1024} == {1<<20}: {256*4*1024 == 1<<20}")
    print(f"  refresh period {p['T_REF']}cyc = {p['T_REF']/mhz:.3f}us "
          f"<= 15.625us: {p['T_REF']/mhz <= 15.625}")
    print("  rd ACK = colcmd+CL+2 (STB+CL+4); wr ACK posted = colcmd+1; "
          "prefetch stream -> 1 word/cyc; cold rd = ACT+T_RCD+CL+3 post-STB")
    return p

def vh(mhz):
    p = params(mhz)
    print("// generated by tools/sdram_calc.py --vh %g -- DO NOT EDIT" % mhz)
    for k, v in sorted(p.items()):
        print("`define SDRAM_%s 32'd%d" % (k, v))
    print("`define SDRAM_CL 32'd2")

if __name__ == "__main__":
    if sys.argv[1:2] == ["--vh"]:
        vh(float(sys.argv[2])); sys.exit(0)
    for m in ([float(a) for a in sys.argv[1:]] or [25, 60, 80]): report(m)
    print("chip bits:", 4*524288*32, "== 64M:", 4*524288*32 == 2**26)
