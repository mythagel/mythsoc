#!/usr/bin/env python3
"""ptmap -- C7 Sv32 page tables for tb_core (mythrv32).

Emits (a) $readmemh image for the TB m2 slave (PA-indexed words),
(b) a verilog-include of constants, (c) an emu-loadable dict (imported by
tools/emu32.py via walk()).

Map (root L1 @ PA 0x3FF000, satp.PPN=0x3FF, asid tests use 0/1):
  VA 0x00000000-003FFFFF  L1[0x000] 4M  PA 0x00000000 R X A      (ROM/code)
  VA 0x10000000-00FFFFFF  L1[0x040] ptr -> L0a@0x3FE000:
      L0a[0x000] 4K PA 0x800000 DRWXAD (alias DRAM+0)
      L0a[0x001] 4K PA 0x800000 R W X A D=0 (4K store->15)
  VA 0x20000000-..        L1[0x080] 4M PA 0x800000 R X A (no W)  (store->15)
  VA 0x30000000-..        L1[0x0C0] 4M PA 0x800010 R W X A U     (S->13, SUM ok)
  VA 0x40000000-..        L1[0x100] invalid (V=0)                (fetch->12)
  VA 0x50000000-..        L1[0x140] 4M PA 0x800020 R W X U A=0   (load->13)
  VA 0x60000000-..        L1[0x180] 4M PA 0x800030 R W X A (D=0) (store->15)
  asid=1 satp: L1 root @ 0x3FD000 -> L1[0x040] ptr L0c@0x3FC000:
      L0c[0] 4K PA 0x800010 (DRAM+0x1000) R W X A D   (asid swap proof)
  everything else invalid.
"""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from mmu_addr import pte

ROOT   = 0x3FF000 >> 12
L0A    = 0x3FE000 >> 12
ROOT1  = 0x3FD000 >> 12
L0C    = 0x3FC000 >> 12

def build():
    m = {}                                        # PA word -> value
    def put(pa, v): m[pa >> 2] = v
    # root L1 (asid0)
    put(0x3FF000 + 4*0x000, pte(v=1,r=1,x=1,a=1,ppn=0x00000))       # 4M PA0
    put(0x3FF000 + 4*0x040, pte(v=1,ppn=L0A))                       # ptr
    put(0x3FF000 + 4*0x080, pte(v=1,r=1,x=1,a=1,ppn=0x80000))       # no W
    put(0x3FF000 + 4*0x0C0, pte(v=1,r=1,w=1,x=1,a=1,u=1,ppn=0x80000))
    put(0x3FF000 + 4*0x140, pte(v=1,r=1,w=1,x=1,u=1,ppn=0x80000))   # A=0
    put(0x3FF000 + 4*0x180, pte(v=1,r=1,w=1,x=1,a=1,ppn=0x80000))   # D=0
    put(0x3FF000 + 4*0x200, pte(v=1,r=1,w=1,x=1,a=1,d=1,ppn=0x80000))  # DRAM
    # L0a
    put(0x3FE000 + 4*0x000, pte(v=1,r=1,w=1,x=1,a=1,d=1,ppn=0x80001))
    put(0x3FE000 + 4*0x001, pte(v=1,r=1,w=1,x=1,a=1,ppn=0x80001))   # D=0 4K
    # root L1 (asid1): same code map + alias page -> PA 0x800004
    put(0x3FD000 + 4*0x000, pte(v=1,r=1,x=1,a=1,ppn=0x00000))
    put(0x3FD000 + 4*0x200, pte(v=1,r=1,w=1,x=1,a=1,d=1,ppn=0x80000))  # DRAM
    put(0x3FD000 + 4*0x040, pte(v=1,ppn=L0C))
    put(0x3FC000 + 4*0x000, pte(v=1,r=1,w=1,x=1,a=1,d=1,ppn=0x80002))
    return m

if __name__ == "__main__":
    m = build()
    mode = sys.argv[1] if len(sys.argv) > 1 else "hex"
    if mode == "hex":                             # $readmemh (word 0..16K)
        out = ["@%x\n%08x" % (k, v) for k, v in sorted(m.items())]
        print("\n".join(out))
    elif mode == "vh":
        s0 = (1 << 31) | (0 << 22) | ROOT
        s1 = (1 << 31) | (1 << 22) | ROOT1
        print("// generated by tools/ptmap.py")
        print("`define SATP_A0 32'h%08X" % s0)
        print("`define SATP_A1 32'h%08X" % s1)
    elif mode == "dump":
        for k, v in sorted(m.items()):
            print("PT[%05x]=%08x" % (k, v))
