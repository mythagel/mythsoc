WDS = [(64, 0x11223344), (68, 0xFFFFFFFF), (72, 0x80000080)]


def byte_at(off):
    for base, w in WDS:
        if base <= off < base + 4:
            return (w >> (8 * (off - base))) & 0xFF
    raise AssertionError


def half_at(off):
    return (byte_at(off + 1) << 8) | byte_at(off)


def sgn8(b):
    return b - 0x100 if b & 0x80 else b


def sgn16(h):
    return h - 0x10000 if h & 0x8000 else h


def load(op, off, exp):
    L.append("    %-3s x2, %d(x1)" % (op, off))
    L.append("    li    x3, %s" % lit(exp))
    chk()


