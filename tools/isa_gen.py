#!/usr/bin/env python3
"""tools/isa_gen.py -- generate tests/t01_isa.S (RV32I + M ISA firmware test).

Every expected value is computed here (AGENTS.md: no hand math).
Spec: unpriv Ch.2 (RV32I, Table 13), Ch.12 (RV32M, Table 15 + Table 11
div/rem semantics). Framework: tests/fw_tb.S (x1 = DRAM base 0x8000_0000).
Check id N fails with result 0x8000_000N.

Usage: python3 tools/isa_gen.py > tests/t01_isa.S
"""

W = 32
M = 0xFFFFFFFF


def w32(v):
    return v & M


def sgn(v):
    v = w32(v)
    return v - (1 << W) if v >> (W - 1) else v


def c_add(a, b):
    return w32(a + b)


def c_sub(a, b):
    return w32(a - b)


def c_sll(a, b):
    return w32(w32(a) << (b & 31))


def c_srl(a, b):
    return w32(w32(a) >> (b & 31))


def c_sra(a, b):
    a, b = w32(a), b & 31
    s = sgn(a)
    if s < 0:
        return w32(s >> b if b else s)
    return w32(a >> b)


def c_slt(a, b):
    return 1 if sgn(a) < sgn(b) else 0


def c_sltu(a, b):
    return 1 if w32(a) < w32(b) else 0


def c_xor(a, b):
    return w32(a ^ b)


def c_or(a, b):
    return w32(a | b)


def c_and(a, b):
    return w32(a & b)


# ---- RV32M (Table 15; div/rem semantics Table 11) -------------------
def m_mul(a, b):
    return w32(a * b)


def m_mulh(a, b):
    return w32((sgn(a) * sgn(b)) >> 32)


def m_mulhsu(a, b):
    return w32((sgn(a) * w32(b)) >> 32)


def m_mulhu(a, b):
    return w32((w32(a) * w32(b)) >> 32)


def m_div(a, b):
    a, b = sgn(a), sgn(b)
    if b == 0:
        return -1                                  # Table 11: quotient all-1
    if a == -(1 << 31) and b == -1:
        return -(1 << 31)                          # overflow: quotient = dividend
    q = abs(a) // abs(b)
    if (a < 0) != (b < 0):
        q = -q
    return q


def m_rem(a, b):
    a, b = sgn(a), sgn(b)
    if b == 0:
        return a
    if a == -(1 << 31) and b == -1:
        return 0
    r = abs(a) % abs(b)
    if a < 0:
        r = -r
    return r


def m_divu(a, b):
    a, b = w32(a), w32(b)
    return -1 if b == 0 else a // b


def m_remu(a, b):
    a, b = w32(a), w32(b)
    return a if b == 0 else a % b


OPS = [("add", c_add), ("sub", c_sub), ("sll", c_sll), ("srl", c_srl),
        ("sra", c_sra), ("slt", c_slt), ("sltu", c_sltu), ("xor", c_xor),
        ("or", c_or), ("and", c_and)]
PAIRS = [(1, 1), (-1, 1), (1, -1), (1 << 31, 1), (1, 1 << 31),
         (0x7FFFFFFF, 1), (-1, -1), (0x12345678, 0x9ABCDEF0)]

MODS = [("mul", m_mul), ("mulh", m_mulh), ("mulhsu", m_mulhsu),
        ("mulhu", m_mulhu), ("div", m_div), ("divu", m_divu),
        ("rem", m_rem), ("remu", m_remu)]
MPAIRS = [(7, 6), (7, 7), (-1, -1), (1 << 31, 1 << 31), (1 << 31, 2),
          (0x10000, 0x10000), (-1, 2), (0xFFFFFFFF, 0xFFFFFFFF),
          (42, 7), (-42, 7), (43, -7), (-43, -7), (-1, -1), (1, 0),
          (-1, 0), (0, 1), (1 << 31, -1), (5, 0), (42, 0),
          (0x80000000, 3), (100, 7)]


def lit(v):
    """literal for `li` (signed decimal or hex)"""
    s = sgn(v)
    if s < 0:
        return str(s)
    return "0x%x" % w32(v)


L = []
nid = [0]


def chk():
    nid[0] += 1
    L.append("    chk %d" % nid[0])


def setup(a, b):
    L.append("    li    x4, %s" % lit(a))
    L.append("    li    x5, %s" % lit(b))


def op(name, a, b, fn, opname=None):
    setup(a, b)
    L.append("    %-3s x2, x4, x5" % (opname or name))
    L.append("    li    x3, %s" % lit(fn(a, b)))
    chk()


def sec(t):
    L.append("    # ======================= %s =======================" % t)


